#!/usr/bin/env python3
"""Set up one business. Requires Python 3.10+ and Docker Compose v2."""
import argparse, getpass, json, os, re, secrets, shutil, subprocess, sys, time, urllib.request
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ENV=ROOT/".env"
BUSINESS=ROOT/"config"/"business.json"
STATE=ROOT/".setup-state.json"

def ask(label, default=None, required=True):
    value=input(f"{label}"+(f" [{default}]" if default else "")+": ").strip() or (default or "")
    if required and not value: raise ValueError(f"{label} is required")
    return value

def secret(): return secrets.token_urlsafe(48)
def compose(*args,check=True):
    return subprocess.run(["docker","compose","--project-directory",str(ROOT),*args],cwd=ROOT,check=check)

def wait_http(url,deadline):
    while time.monotonic()<deadline:
        try:
            with urllib.request.urlopen(url,timeout=3) as response:
                if response.status == 200: return
        except Exception:
            pass
        time.sleep(3)
    raise TimeoutError(f"Service not healthy: {url}")

def write_private(path,text):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    with os.fdopen(fd,"w",encoding="utf-8") as f:f.write(text)

def main():
    parser=argparse.ArgumentParser(description="Set up one business")
    parser.add_argument("--start-only",action="store_true",help="Start the services. Check their health.")
    parser.add_argument("--skip-admin",action="store_true",help="Do not create a Strapi administrator.")
    parser.add_argument("--timeout",type=int,default=480)
    args=parser.parse_args()
    if not shutil.which("docker"): sys.exit("Docker is not installed. Install Docker and try again.")
    subprocess.run(["docker","compose","version"],check=True)
    if args.timeout<30:sys.exit("--timeout must be >=30 seconds")
    if not args.start_only and not ENV.exists():
        print("=== Set up a business ===")
        name=ask("Company name")
        slug=ask("Company ID (lowercase letters, numbers, and hyphens)",re.sub(r"[^a-z0-9]+","-",name.lower()).strip("-"))
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*",slug):raise ValueError("The company ID is not valid. Use lowercase letters, numbers, and hyphens.")
        email=ask("Company email address")
        if "@" not in email or any(c.isspace() for c in email):raise ValueError("The email address is not valid. Check the address.")
        timezone=ask("IANA time zone","Europe/Berlin")
        from zoneinfo import ZoneInfo
        ZoneInfo(timezone)
        language=ask("Language code","de")
        if not re.fullmatch(r"[a-z]{2}(?:-[A-Z]{2})?",language):raise ValueError("The language code is not valid. Check the code.")
        currency=ask("Currency (ISO 4217)","EUR").upper()
        if not re.fullmatch("[A-Z]{3}",currency):raise ValueError("The currency code is not valid. Use three uppercase letters.")
        address=ask("Company address (optional)",required=False)
        phone=ask("Company phone number (optional)",required=False)
        print("\nCompany details:",name,email,timezone,language,currency)
        if ask("Save these details? (yes/no)","no") != "yes":sys.exit("Cancelled")
        settings={"name":name,"slug":slug,"contactEmail":email,"timezone":timezone,"locale":language,"currency":currency,"address":address,"phone":phone}
        write_private(BUSINESS,json.dumps(settings,indent=2,ensure_ascii=False)+"\n")
        values={
          "POSTGRES_PASSWORD":secret(),"CMS_DB_PASSWORD":secret(),
          "STRAPI_APP_KEYS":",".join(secret() for _ in range(4)),
          "STRAPI_API_TOKEN_SALT":secret(),"STRAPI_ADMIN_JWT_SECRET":secret(),
          "STRAPI_JWT_SECRET":secret(),"STRAPI_TRANSFER_TOKEN_SALT":secret(),
          "STRAPI_ENCRYPTION_KEY":secret(),
        }
        write_private(ENV,"# Generated by scripts/setup.py. Never commit this file.\n"+"".join(f"{k}={v}\n" for k,v in values.items()))
        print("Saved the configuration and private secret files.")
    if not ENV.exists():sys.exit("The .env file does not exist. Run sh setup.sh first.")
    print("Start the Docker Compose services.")
    compose("up","-d","--build")
    deadline=time.monotonic()+args.timeout
    print("Check the Spring Boot and Strapi health endpoints.")
    wait_http("http://127.0.0.1:8080/actuator/health",deadline)
    wait_http("http://127.0.0.1:1337/_health",deadline)
    print("Both services passed the health checks.")
    if not args.start_only and not args.skip_admin and not STATE.exists():
        print("\nCreate the first technical Strapi administrator.")
        print("Enter the name, email address, and password when Strapi asks for them.")
        print("This account is only for Strapi. It cannot sign in to the custom Angular admin.")
        if ask("Create the Strapi administrator now? (yes/no)","yes")=="yes":
            result=compose("exec","cms","npm","run","strapi","--","admin:create-user",check=False)
            if result.returncode!=0:
                print("Strapi did not create the administrator. Run this command:")
                print("  docker compose exec cms npm run strapi -- admin:create-user")
                return 1
            write_private(STATE,json.dumps({"strapiAdminCliCompleted":True,"version":1})+"\n")
        else:print("The administrator was not created. Run setup again to create it.")
    print("\nStrapi admin address: http://127.0.0.1:1337/admin")
    print("Backend health address: http://127.0.0.1:8080/actuator/health")
    print("This command does not start Angular. It does not connect Google or Stripe. It does not set up HTTPS.")
    return 0

if __name__=="__main__":
    try:sys.exit(main())
    except (OSError,ValueError,subprocess.CalledProcessError,TimeoutError,KeyboardInterrupt) as e:
        sys.exit(f"Setup stopped: {e}. Your files are still present. Correct the problem and run setup again.")
