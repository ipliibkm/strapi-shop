#!/usr/bin/env python3
"""Interactive single-business bootstrap. Requires Python 3.10+ and Docker Compose v2."""
import argparse, getpass, json, os, re, secrets, shutil, subprocess, sys, time, urllib.request
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ENV=ROOT/".env"
BUSINESS=ROOT/"config"/"business.json"
STATE=ROOT/".setup-state.json"

def ask(label, default=None, required=True):
    value=input(f"{label}"+(f" [{default}]" if default else "")+": ").strip() or (default or "")
    if required and not value: raise ValueError(f"{label} is required")
    return value

def secret(): return secrets.token_urlsafe(48)
def compose(*args,check=True):
    return subprocess.run(["docker","compose","--project-directory",str(ROOT),*args],cwd=ROOT,check=check)

def wait_http(url,deadline):
    while time.monotonic()<deadline:
        try:
            with urllib.request.urlopen(url,timeout=3) as response:
                if response.status == 200: return
        except Exception:
            pass
        time.sleep(3)
    raise TimeoutError(f"Service not healthy: {url}")

def write_private(path,text):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    with os.fdopen(fd,"w",encoding="utf-8") as f:f.write(text)

def main():
    parser=argparse.ArgumentParser(description="Set up one business installation")
    parser.add_argument("--start-only",action="store_true",help="Start existing instance and wait for health")
    parser.add_argument("--skip-admin",action="store_true",help="Defer initial Strapi admin creation")
    parser.add_argument("--timeout",type=int,default=480)
    args=parser.parse_args()
    if not shutil.which("docker"): sys.exit("Docker CLI is missing")
    subprocess.run(["docker","compose","version"],check=True)
    if args.timeout<30:sys.exit("--timeout must be >=30 seconds")
    if not args.start_only and not ENV.exists():
        print("=== New business installation ===")
        name=ask("Company / public brand name")
        slug=ask("Company slug (lowercase a-z, 0-9, hyphens)",re.sub(r"[^a-z0-9]+","-",name.lower()).strip("-"))
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*",slug):raise ValueError("Invalid company slug")
        email=ask("Public contact email")
        if "@" not in email or any(c.isspace() for c in email):raise ValueError("Invalid email")
        timezone=ask("IANA time zone","Europe/Berlin")
        from zoneinfo import ZoneInfo
        ZoneInfo(timezone)
        language=ask("Primary language code","de")
        if not re.fullmatch(r"[a-z]{2}(?:-[A-Z]{2})?",language):raise ValueError("Invalid language")
        currency=ask("Currency (ISO 4217)","EUR").upper()
        if not re.fullmatch("[A-Z]{3}",currency):raise ValueError("Invalid currency")
        address=ask("Business street/address (optional)",required=False)
        phone=ask("Public phone (optional)",required=False)
        print("\nBusiness configuration:",name,email,timezone,language,currency)
        if ask("Create this installation? (yes/no)","no") != "yes":sys.exit("Cancelled")
        settings={"name":name,"slug":slug,"contactEmail":email,"timezone":timezone,"locale":language,"currency":currency,"address":address,"phone":phone}
        write_private(BUSINESS,json.dumps(settings,indent=2,ensure_ascii=False)+"\n")
        values={
          "POSTGRES_PASSWORD":secret(),"CMS_DB_PASSWORD":secret(),
          "STRAPI_APP_KEYS":",".join(secret() for _ in range(4)),
          "STRAPI_API_TOKEN_SALT":secret(),"STRAPI_ADMIN_JWT_SECRET":secret(),
          "STRAPI_JWT_SECRET":secret(),"STRAPI_TRANSFER_TOKEN_SALT":secret(),
          "STRAPI_ENCRYPTION_KEY":secret(),
        }
        write_private(ENV,"# Generated by scripts/setup.py. Never commit this file.\n"+"".join(f"{k}={v}\n" for k,v in values.items()))
        print("Created private .env and config/business.json.")
    if not ENV.exists():sys.exit("Missing .env. Run without --start-only first.")
    print("Starting Docker Compose services...")
    compose("up","-d","--build")
    deadline=time.monotonic()+args.timeout
    print("Waiting for Spring Boot and Strapi health...")
    wait_http("http://127.0.0.1:8080/actuator/health",deadline)
    wait_http("http://127.0.0.1:1337/_health",deadline)
    print("Service health checks passed.")
    if not args.start_only and not args.skip_admin and not STATE.exists():
        print("\nCreate initial technical Strapi administrator.")
        print("You will enter the admin name, email and password in the Strapi interactive CLI.")
        print("This technical account is not yet an account for the planned custom Angular admin.")
        if ask("Run Strapi administrator creation now? (yes/no)","yes")=="yes":
            result=compose("exec","cms","npm","run","strapi","--","admin:create-user",check=False)
            if result.returncode!=0:
                print("Administrator creation not completed. Retry manually:")
                print("  docker compose exec cms npm run strapi -- admin:create-user")
                return 1
            write_private(STATE,json.dumps({"strapiAdminCliCompleted":True,"version":1})+"\n")
        else:print("Admin creation skipped; run setup again or use the CLI.")
    print("\nStarted. Strapi technical admin: http://127.0.0.1:1337/admin")
    print("Backend health: http://127.0.0.1:8080/actuator/health")
    print("Note: Angular admin/storefront, Google, payment and hardened TLS ingress are not deployed by this command.")
    return 0

if __name__=="__main__":
    try:sys.exit(main())
    except (OSError,ValueError,subprocess.CalledProcessError,TimeoutError,KeyboardInterrupt) as e:
        sys.exit(f"Setup failed: {e}. Your data was retained; rerun setup after fixing the issue.")
